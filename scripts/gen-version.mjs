// Write a package's version into `src/version.generated.ts`, so the runtime can report
// which build is actually loaded without importing package.json (which bundlers and ESM
// resolvers handle inconsistently, and which would drag the whole manifest into the
// bundle).
//
// Run from a package directory: `node ../../scripts/gen-version.mjs`
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = process.cwd();
const { name, version } = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
const out = join(dir, 'src', 'version.generated.ts');

writeFileSync(
  out,
  `// GENERATED by scripts/gen-version.mjs. Do not edit.\n` +
    `\n` +
    `/** The published version of ${name} that this build came from. */\n` +
    `export const VERSION = '${version}';\n`,
);

console.log(`✓ ${name}@${version}`);
