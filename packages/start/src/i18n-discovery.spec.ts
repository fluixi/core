import { describe, it, expect, afterEach } from 'vitest';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { i18nVitePlugin, startTypesPlugin } from './internal.js';
import { resolveConfig } from './config.js';

describe('i18n auto-discovery', () => {
  const dirs: string[] = [];
  afterEach(() => {
    while (dirs.length) rmSync(dirs.pop()!, { recursive: true, force: true });
  });

  it('discovers <locale>.json under the dir → virtual:fluixi-i18n', () => {
    const root = mkdtempSync(join(tmpdir(), 'fx-i18n-'));
    dirs.push(root);
    mkdirSync(join(root, 'src/i18n'), { recursive: true });
    writeFileSync(join(root, 'src/i18n/en.json'), JSON.stringify({ hi: 'Hello' }));
    writeFileSync(join(root, 'src/i18n/fr.json'), JSON.stringify({ hi: 'Bonjour' }));

    const p: any = i18nVitePlugin({ dir: 'src/i18n' });
    p.configResolved({ root });
    expect(p.resolveId('virtual:fluixi-i18n')).toBe('\0virtual:fluixi-i18n');
    const code = p.load('\0virtual:fluixi-i18n') as string;
    expect(code).toContain('en.json');
    expect(code).toContain('fr.json');
    expect(code).toContain('export const locales = ["en","fr"]');
    expect(code).toContain('export const defaultLocale = "en"');
    expect(code).toContain('export const messages');
  });

  it('honors an explicit defaultLocale, and is empty when the folder is missing', () => {
    const root = mkdtempSync(join(tmpdir(), 'fx-i18n-'));
    dirs.push(root);
    const p: any = i18nVitePlugin({ dir: 'src/i18n', defaultLocale: 'fr' });
    p.configResolved({ root });
    const code = p.load('\0virtual:fluixi-i18n') as string;
    expect(code).toContain('export const locales = []');
    expect(code).toContain('export const defaultLocale = "fr"');
  });

  it('config: i18n defaults to enabled (src/i18n); false disables it', () => {
    expect(resolveConfig({}).i18n).toEqual({ dir: 'src/i18n', defaultLocale: undefined, locales: undefined });
    expect(resolveConfig({ i18n: false }).i18n).toBe(false);
    expect(resolveConfig({ i18n: { dir: 'locales', locales: ['en'] } }).i18n).toMatchObject({ dir: 'locales', locales: ['en'] });
  });

  it('auto-generates the virtual-module .d.ts (apps never hand-write them)', () => {
    const root = mkdtempSync(join(tmpdir(), 'fx-types-'));
    dirs.push(root);
    mkdirSync(join(root, 'src'), { recursive: true });
    const p: any = startTypesPlugin(resolveConfig({ root }));
    p.configResolved({ root });
    p.buildStart();
    const d = readFileSync(join(root, 'src/fluixi-start-env.d.ts'), 'utf8');
    expect(d).toContain("declare module 'virtual:fluixi-server-fns'");
    expect(d).toContain("declare module 'virtual:fluixi-i18n'"); // i18n on by default
    expect(d).toContain('handleServerFn');
    expect(d).toContain('Auto-generated by @fluixi/start');
  });
});
