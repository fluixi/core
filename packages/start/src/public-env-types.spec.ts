import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { envFileNames, envTypes, startTypesPlugin } from './internal.js';
import { resolveConfig } from './config.js';

let root = '';
afterEach(() => {
  if (root) rmSync(root, { recursive: true, force: true });
  root = '';
});

const app = (files: Record<string, string> = {}) => {
  root = mkdtempSync(join(tmpdir(), 'fluixi-types-'));
  mkdirSync(join(root, 'src'));
  for (const [name, text] of Object.entries(files)) writeFileSync(join(root, name), text);
};
const run = (publicNames: string[]) => {
  const plugin = startTypesPlugin(resolveConfig({ root, env: { public: publicNames }, i18n: false }));
  plugin.configResolved({ root });
  plugin.buildStart();
};
const file = () => join(root, 'src/fluixi-env-vars.d.ts');

describe('the generated env declaration', () => {
  it('augments @fluixi/start/env with both sets, quoting a name that is not an identifier', () => {
    const out = envTypes(['API_URL', 'my-flag'], ['SESSION_SECRET', 'API_URL', 'VITE_OLD']);
    expect(out).toContain("declare module '@fluixi/start/env'");
    expect(out).toMatch(/interface PublicEnv \{\n {4}API_URL: string;\n {4}"my-flag": string;\n {2}\}/);
    // Public names are not repeated as server names, and VITE_ is covered by the type already.
    expect(out).toMatch(/interface ServerEnv \{\n {4}SESSION_SECRET: string;\n {2}\}/);
    expect(out).toContain('export {};');
  });

  it('reads names from the env files and never a value', () => {
    app({ '.env': 'SESSION_SECRET=hunter2\n# COMMENTED=1\nexport API_URL = "x"\n', '.env.example': 'OIDC_CLIENT_SECRET=\n' });
    expect(envFileNames(root)).toEqual(['API_URL', 'OIDC_CLIENT_SECRET', 'SESSION_SECRET']);
    run(['API_URL']);
    const out = readFileSync(file(), 'utf8');
    expect(out).toContain('SESSION_SECRET: string;');
    expect(out).not.toContain('hunter2');
  });

  it('rewrites it when the set changes', () => {
    app();
    run(['API_URL']);
    run(['API_URL', 'APP_URL']);
    expect(readFileSync(file(), 'utf8')).toContain('APP_URL: string;');
  });

  it('removes the one it wrote once there is nothing to declare, and never a file of the app', () => {
    app();
    run(['API_URL']);
    run([]);
    expect(existsSync(file())).toBe(false);

    writeFileSync(file(), '// written by hand\n');
    run([]);
    expect(readFileSync(file(), 'utf8')).toBe('// written by hand\n');
  });

  it('removes the file under its earlier name when start wrote it', () => {
    app();
    const old = join(root, 'src/fluixi-public-env.d.ts');
    writeFileSync(old, '// Auto-generated by @fluixi/start from env.public in fluixi.config.ts, do not edit.\n');
    run(['API_URL']);
    expect(existsSync(old)).toBe(false);
    expect(existsSync(file())).toBe(true);
  });
});
