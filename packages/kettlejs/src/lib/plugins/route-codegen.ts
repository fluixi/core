/**
 * @fileoverview Route code generator
 * @module @awc/kettlejs/plugins/route-codegen
 *
 * Generates an ES module from a ScannedRoute tree.
 * Uses lazy() for code-split component loading with Suspense integration.
 */

import type { ScannedRoute } from './route-scanner.js';

/**
 * Collect all routes into a flat list for import generation.
 */
function collectRoutes(routes: ScannedRoute[], out: ScannedRoute[] = []): ScannedRoute[] {
  for (const route of routes) {
    out.push(route);
    if (route.children.length > 0) {
      collectRoutes(route.children, out);
    }
  }
  return out;
}

/**
 * Generate a virtual ES module string from a scanned route tree.
 */
export function generateRouteModule(
  routes: ScannedRoute[],
  routesDir: string
): string {
  const lines: string[] = [];

  lines.push(`// Auto-generated by @awc/kettlejs route plugin`);
  lines.push(`// Do not edit manually`);
  lines.push(``);
  lines.push(`import { lazy } from '@awc/kettlejs/router';`);
  lines.push(``);
  lines.push(`export const routes = ${generateRouteArray(routes, routesDir, 0)};`);
  lines.push(``);

  return lines.join('\n');
}

function generateRouteArray(
  routes: ScannedRoute[],
  routesDir: string,
  depth: number
): string {
  if (routes.length === 0) return '[]';

  const indent = '  '.repeat(depth);
  const items = routes.map((route) => generateRouteObject(route, routesDir, depth + 1));

  return `[\n${items.join(',\n')}\n${indent}]`;
}

function generateRouteObject(
  route: ScannedRoute,
  routesDir: string,
  depth: number
): string {
  const indent = '  '.repeat(depth);
  const props: string[] = [];
  const importPath = buildImportPath(route.filePath, routesDir);

  // Path
  const routePath = computeRoutePath(route);
  props.push(`${indent}  path: ${JSON.stringify(routePath)}`);

  // Component — lazy-loaded via dynamic import + Suspense
  props.push(`${indent}  component: lazy(() => import(${JSON.stringify(importPath)}))`);

  // Data loader — dynamic import, calls routeData if exported
  props.push(`${indent}  data: (args) => import(${JSON.stringify(importPath)}).then(m => m.routeData ? m.routeData(args) : undefined)`);

  // Children
  if (route.children.length > 0) {
    const childArray = generateRouteArray(route.children, routesDir, depth + 1);
    props.push(`${indent}  children: ${childArray}`);
  }

  return `${indent}{\n${props.join(',\n')}\n${indent}}`;
}

/**
 * Compute the route path for a RouteDefinition.
 */
function computeRoutePath(route: ScannedRoute): string {
  if (route.isLayout) {
    return extractLayoutPath(route);
  }
  if (route.isIndex) {
    return '/';
  }
  return `/${route.urlSegment}`;
}

function extractLayoutPath(route: ScannedRoute): string {
  const dir = route.filePath.replace(/\/layout\.[^.]+$/, '');
  if (!dir || dir === route.filePath) {
    return '/';
  }
  return '/' + dir;
}

/**
 * Build the import path for a route file.
 */
function buildImportPath(filePath: string, routesDir: string): string {
  const base = routesDir.replace(/\\/g, '/').replace(/\/$/, '');
  return `${base}/${filePath}`;
}
