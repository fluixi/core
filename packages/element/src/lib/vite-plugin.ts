/**
 * @fileoverview Vite plugin that auto-generates global type augmentations
 * for defineElement() calls. Scans source files for defineElement('tag-name', ...)
 * and writes a kettle-elements.d.ts with KettleElements + HTMLElementTagNameMap entries.
 * @module @awc/element/vite-plugin
 */

import fs from 'fs';
import path from 'path';

interface ElementEntry {
  tagName: string;
  varName: string;
  filePath: string;
}

const DEFINE_ELEMENT_RE =
  /(?:const|let|var)\s+(\w+)\s*=\s*defineElement\(\s*['"]([a-z][\w-]*)['"]/g;

function extractElements(code: string, filePath: string): ElementEntry[] {
  const entries: ElementEntry[] = [];
  let match: RegExpExecArray | null;
  DEFINE_ELEMENT_RE.lastIndex = 0;
  while ((match = DEFINE_ELEMENT_RE.exec(code)) !== null) {
    entries.push({
      varName: match[1],
      tagName: match[2],
      filePath,
    });
  }
  return entries;
}

function scanDir(dir: string, entries: Map<string, ElementEntry[]>): void {
  if (!fs.existsSync(dir)) return;
  const items = fs.readdirSync(dir);
  for (const item of items) {
    const full = path.join(dir, item);
    const stat = fs.statSync(full);
    if (stat.isDirectory()) {
      if (item === 'node_modules' || item === 'dist' || item === '.git')
        continue;
      scanDir(full, entries);
    } else if (/\.(ts|tsx|js|jsx)$/.test(item)) {
      const code = fs.readFileSync(full, 'utf-8');
      if (code.includes('defineElement')) {
        const found = extractElements(code, full);
        if (found.length > 0) {
          entries.set(full, found);
        }
      }
    }
  }
}

function generateDts(entries: ElementEntry[], outDir: string): string {
  if (entries.length === 0) {
    return [
      '// Auto-generated by @awc/element/vite-plugin — do not edit',
      '// No defineElement calls found',
      '',
      'export {};',
      '',
    ].join('\n');
  }

  const importLines: string[] = [];
  const jsxEntries: string[] = [];
  const htmlMapEntries: string[] = [];

  // Group entries by import path to generate named imports
  const importsByPath = new Map<string, string[]>();

  for (const entry of entries) {
    const relPath = path.posix.normalize(
      path
        .relative(outDir, entry.filePath)
        .replace(/\\/g, '/')
        .replace(/\.(ts|tsx|js|jsx)$/, '')
    );
    const importPath = relPath.startsWith('.') ? relPath : `./${relPath}`;

    const vars = importsByPath.get(importPath);
    if (vars) {
      vars.push(entry.varName);
    } else {
      importsByPath.set(importPath, [entry.varName]);
    }

    jsxEntries.push(
      `    '${entry.tagName}': KettleElementJSXAttributes<typeof ${entry.varName}>;`
    );
    htmlMapEntries.push(
      `    '${entry.tagName}': InstanceType<typeof ${entry.varName}>;`
    );
  }

  for (const [importPath, vars] of importsByPath) {
    importLines.push(`import type { ${vars.join(', ')} } from '${importPath}';`);
  }

  const lines: string[] = [
    '// Auto-generated by @awc/element/vite-plugin — do not edit',
    `import type { KettleElementJSXAttributes } from '@awc/element';`,
    ...importLines,
    '',
    'declare global {',
    '  interface HTMLElementTagNameMap {',
    ...htmlMapEntries,
    '  }',
    '}',
    '',
    "declare module '@awc/jsx-runtime' {",
    '  namespace JSX {',
    '    interface IntrinsicElements {',
    ...jsxEntries,
    '    }',
    '  }',
    '}',
    '',
    'export {};',
    '',
  ];

  return lines.join('\n');
}

export interface KettleElementPluginOptions {
  /** Output path for the generated .d.ts file. Default: 'src/kettle-elements.d.ts' */
  dts?: string;
  /** Source directory to scan on startup. Default: 'src' */
  srcDir?: string;
}

export function kettleElementPlugin(
  options: KettleElementPluginOptions = {}
): any {
  const { dts = 'src/kettle-elements.d.ts', srcDir = 'src' } = options;

  let root = '';
  const allEntries = new Map<string, ElementEntry[]>();

  function writeDtsFile() {
    const entries = Array.from(allEntries.values()).flat();
    const outPath = path.resolve(root, dts);
    const outDir = path.dirname(outPath);
    const content = generateDts(entries, outDir);

    if (!fs.existsSync(outDir)) {
      fs.mkdirSync(outDir, { recursive: true });
    }

    try {
      const existing = fs.readFileSync(outPath, 'utf-8');
      if (existing === content) return;
    } catch {
      // File doesn't exist yet
    }

    fs.writeFileSync(outPath, content, 'utf-8');
  }

  return {
    name: 'kettle-element-dts',
    enforce: 'pre' as const,

    configResolved(config: any) {
      root = config.root;
    },

    buildStart() {
      allEntries.clear();
      const scanPath = path.resolve(root, srcDir);
      scanDir(scanPath, allEntries);
      writeDtsFile();
    },

    transform(code: string, id: string) {
      if (!/\.(ts|tsx|js|jsx)$/.test(id)) return null;
      if (!code.includes('defineElement')) {
        if (allEntries.has(id)) {
          allEntries.delete(id);
          writeDtsFile();
        }
        return null;
      }

      const entries = extractElements(code, id);
      if (entries.length > 0) {
        allEntries.set(id, entries);
        writeDtsFile();
      } else if (allEntries.has(id)) {
        allEntries.delete(id);
        writeDtsFile();
      }

      return null;
    },
  };
}
